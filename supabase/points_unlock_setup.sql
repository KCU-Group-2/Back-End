-- =========================================================
-- StudySwap Points / Unlock / Library backend setup
-- =========================================================


-- ---------------------------------------------------------
-- 1. User profile + point balance
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.profiles (
    user_id UUID PRIMARY KEY
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    points INTEGER NOT NULL DEFAULT 50
        CHECK (points >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ---------------------------------------------------------
-- 2. User-resource unlock history
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.resource_unlocks (
    user_id UUID NOT NULL
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    resource_id BIGINT NOT NULL
        REFERENCES public.resources(id)
        ON DELETE CASCADE,

    points_spent INTEGER NOT NULL DEFAULT 10
        CHECK (points_spent >= 0),

    unlocked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (user_id, resource_id)
);


-- ---------------------------------------------------------
-- 3. Point transaction history
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.point_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    amount INTEGER NOT NULL,

    transaction_type TEXT NOT NULL,

    resource_id BIGINT
        REFERENCES public.resources(id)
        ON DELETE SET NULL,

    request_id BIGINT
        REFERENCES public.resource_requests(id)
        ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ---------------------------------------------------------
-- 4. Every resource costs 10P by default
-- ---------------------------------------------------------

ALTER TABLE public.resources
ADD COLUMN IF NOT EXISTS unlock_cost INTEGER
NOT NULL DEFAULT 10
CHECK (unlock_cost >= 0);


-- ---------------------------------------------------------
-- 5. RLS
-- Backend accesses these tables using service_role.
-- ---------------------------------------------------------

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resource_unlocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.point_transactions ENABLE ROW LEVEL SECURITY;


GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.profiles
TO service_role;

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.resource_unlocks
TO service_role;

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE public.point_transactions
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.point_transactions_id_seq
TO service_role;


-- ---------------------------------------------------------
-- 6. Signup -> automatically give 50P
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.handle_new_user_profile()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN

    INSERT INTO public.profiles (
        user_id,
        points
    )
    VALUES (
        NEW.id,
        50
    )
    ON CONFLICT (user_id) DO NOTHING;

    INSERT INTO public.point_transactions (
        user_id,
        amount,
        transaction_type
    )
    VALUES (
        NEW.id,
        50,
        'signup_bonus'
    );

    RETURN NEW;

END;
$$;


DROP TRIGGER IF EXISTS on_auth_user_created_profile
ON auth.users;


CREATE TRIGGER on_auth_user_created_profile
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user_profile();


-- Existing accounts also need profiles.
INSERT INTO public.profiles (
    user_id,
    points
)
SELECT
    id,
    50
FROM auth.users
ON CONFLICT (user_id) DO NOTHING;


-- Record signup bonus for existing accounts once.
INSERT INTO public.point_transactions (
    user_id,
    amount,
    transaction_type
)
SELECT
    u.id,
    50,
    'signup_bonus'
FROM auth.users u
WHERE NOT EXISTS (
    SELECT 1
    FROM public.point_transactions pt
    WHERE pt.user_id = u.id
      AND pt.transaction_type = 'signup_bonus'
);


-- ---------------------------------------------------------
-- 7. Resource upload -> +20P automatically
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.award_resource_upload_points()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN

    IF NEW.uploader_id IS NOT NULL THEN

        INSERT INTO public.profiles (
            user_id,
            points
        )
        VALUES (
            NEW.uploader_id,
            50
        )
        ON CONFLICT (user_id) DO NOTHING;

        UPDATE public.profiles
        SET points = points + 20
        WHERE user_id = NEW.uploader_id;

        INSERT INTO public.point_transactions (
            user_id,
            amount,
            transaction_type,
            resource_id
        )
        VALUES (
            NEW.uploader_id,
            20,
            'resource_upload',
            NEW.id
        );

    END IF;

    RETURN NEW;

END;
$$;


DROP TRIGGER IF EXISTS on_resource_uploaded_points
ON public.resources;


CREATE TRIGGER on_resource_uploaded_points
AFTER INSERT ON public.resources
FOR EACH ROW
EXECUTE FUNCTION public.award_resource_upload_points();


-- ---------------------------------------------------------
-- 8. Request fulfilled -> uploader receives extra +10P
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.award_request_fulfillment_points()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    uploader UUID;
BEGIN

    IF NEW.status = 'fulfilled'
       AND OLD.status IS DISTINCT FROM 'fulfilled'
       AND NEW.fulfilled_resource_id IS NOT NULL THEN

        SELECT uploader_id
        INTO uploader
        FROM public.resources
        WHERE id = NEW.fulfilled_resource_id;

        IF uploader IS NOT NULL THEN

            UPDATE public.profiles
            SET points = points + 10
            WHERE user_id = uploader;

            INSERT INTO public.point_transactions (
                user_id,
                amount,
                transaction_type,
                resource_id,
                request_id
            )
            VALUES (
                uploader,
                10,
                'request_fulfilled',
                NEW.fulfilled_resource_id,
                NEW.id
            );

        END IF;

    END IF;

    RETURN NEW;

END;
$$;


DROP TRIGGER IF EXISTS on_request_fulfilled_points
ON public.resource_requests;


CREATE TRIGGER on_request_fulfilled_points
AFTER UPDATE ON public.resource_requests
FOR EACH ROW
EXECUTE FUNCTION public.award_request_fulfillment_points();


-- ---------------------------------------------------------
-- 9. Atomic Unlock operation
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.unlock_resource(
    p_user_id UUID,
    p_resource_id BIGINT
)
RETURNS TABLE (
    result_status TEXT,
    remaining_points INTEGER,
    charged_points INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    resource_cost INTEGER;
    resource_uploader UUID;
    current_points INTEGER;
BEGIN

    SELECT
        COALESCE(unlock_cost, 10),
        uploader_id
    INTO
        resource_cost,
        resource_uploader
    FROM public.resources
    WHERE id = p_resource_id;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT
            'not_found'::TEXT,
            NULL::INTEGER,
            NULL::INTEGER;
        RETURN;
    END IF;


    INSERT INTO public.profiles (
        user_id,
        points
    )
    VALUES (
        p_user_id,
        50
    )
    ON CONFLICT (user_id) DO NOTHING;


    SELECT p.points
    INTO current_points
    FROM public.profiles p
    WHERE p.user_id = p_user_id
    FOR UPDATE;


    -- The uploader always has access to their own resource.
    IF resource_uploader = p_user_id THEN

        RETURN QUERY
        SELECT
            'owner'::TEXT,
            current_points,
            0;

        RETURN;
    END IF;


    -- Do not charge twice.
    IF EXISTS (
        SELECT 1
        FROM public.resource_unlocks
        WHERE user_id = p_user_id
          AND resource_id = p_resource_id
    ) THEN

        RETURN QUERY
        SELECT
            'already_unlocked'::TEXT,
            current_points,
            0;

        RETURN;
    END IF;


    -- Not enough points.
    IF current_points < resource_cost THEN

        RETURN QUERY
        SELECT
            'insufficient_points'::TEXT,
            current_points,
            resource_cost;

        RETURN;
    END IF;


    UPDATE public.profiles p
    SET points = p.points - resource_cost
    WHERE p.user_id = p_user_id
    RETURNING p.points
    INTO current_points;


    INSERT INTO public.resource_unlocks (
        user_id,
        resource_id,
        points_spent
    )
    VALUES (
        p_user_id,
        p_resource_id,
        resource_cost
    );


    INSERT INTO public.point_transactions (
        user_id,
        amount,
        transaction_type,
        resource_id
    )
    VALUES (
        p_user_id,
        -resource_cost,
        'resource_unlock',
        p_resource_id
    );


    RETURN QUERY
    SELECT
        'unlocked'::TEXT,
        current_points,
        resource_cost;

END;
$$;


GRANT EXECUTE
ON FUNCTION public.unlock_resource(UUID, BIGINT)
TO service_role;